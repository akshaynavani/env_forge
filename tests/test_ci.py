import yaml

from env_forge.ci import get_generator
from env_forge.ci.affected import affected_components


def test_github_workflow_structure(manifest):
    data = yaml.safe_load(get_generator("github", manifest).render())
    jobs = data["jobs"]
    assert set(jobs) == {"lock-check", "test"}
    matrix = jobs["test"]["strategy"]["matrix"]
    assert matrix["component"] == ["api", "common", "worker"]
    assert matrix["python"] == ["3.10", "3.11"]
    runs = [s.get("run", "") for s in jobs["test"]["steps"]]
    assert any("envforge test ${{ matrix.component }} --ephemeral" in r for r in runs)
    # PyYAML parses the unquoted key `on` as boolean True
    assert True in data or "on" in data


def test_github_affected_only_adds_plan_job(manifest):
    manifest.ci["affected_only"] = True
    data = yaml.safe_load(get_generator("github", manifest).render())
    assert "plan" in data["jobs"]
    assert data["jobs"]["test"]["needs"] == ["plan"]


def test_gitlab_pipeline_uses_dind_for_docker_components(manifest):
    data = yaml.safe_load(get_generator("gitlab", manifest).render())
    test = data["test"]
    assert test["parallel"]["matrix"][0]["COMPONENT"] == ["api", "common", "worker"]
    assert "docker:dind" in test["services"]
    assert data["lock-check"]["script"][-1] == "envforge lock --check"


def test_render_has_do_not_edit_header(manifest):
    assert get_generator("gitlab", manifest).render().startswith("# Generated by envforge")


def test_affected_includes_reverse_dependencies(manifest):
    assert affected_components(manifest, ["libs/common/util.py"]) == ["api", "common"]
    assert affected_components(manifest, ["services/worker/main.py"]) == ["worker"]
    assert affected_components(manifest, ["README.md"]) == []
    assert affected_components(manifest, ["envforge.lock"]) == ["api", "common", "worker"]
